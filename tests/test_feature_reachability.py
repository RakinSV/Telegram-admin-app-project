@pytest.mark.parametrize("func,home,damage", ENTRY_POINTS)
def test_entry_point_is_called_from_production(func, home, damage):
    # Вызов ИЛИ передача ссылкой. Часть точек входа никто не вызывает по
    # имени: их отдают планировщику или очереди, и там имя стоит перед
    # запятой, а не перед скобкой. Искать только «имя(» значило бы объявлять
    # мёртвыми ровно те фичи, что работают по расписанию. Голое упоминание в
    # импорте под правило не подходит — за ним нет ни скобки, ни запятой.
    used = re.compile(rf"\b{re.escape(func)}\s*[(,)\]]")
    callers = [
        str(path) for path, text in _production_sources()
        if path.name != home and used.search(text)
    ]

    assert callers, f"{func}: никто не зовёт и никому не передаёт — {damage}"
