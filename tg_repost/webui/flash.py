"""Сообщение, переживающее переадресацию (юзабилити, 2026-08-17).

ЗАЧЕМ. После POST страница отвечает переадресацией — так и надо, иначе
обновление страницы повторяет действие. Но при этом теряется всё, что
хотелось сказать: обработчик, наткнувшийся на неверный ввод, просто
возвращал человека обратно. Тот видел ту же страницу без единого слова и не
понимал, случилось ли что-нибудь вообще.

Аудит путей нашёл 53 таких перехода. Большинство — переадресация ПОСЛЕ
УСПЕХА, там объяснять нечего: изменение видно на самой странице. Опасны
остальные: отказ, который выглядит как бездействие.

СООБЩЕНИЕ ОДНОРАЗОВОЕ. Читается ровно один раз и тут же удаляется из
сессии; иначе оно висело бы на каждой следующей странице, объясняя давно
забытое действие.

ХРАНИТСЯ В СЕССИИ, А НЕ В АДРЕСЕ. Параметр строки запроса оседает в истории
браузера и логах прокси — и текст ошибки вместе с ним. Сессия уже подписана
и живёт ровно столько, сколько нужно.
"""

from __future__ import annotations

from typing import Literal

from fastapi import Request
from jinja2 import pass_context

_KEY = "flash"

Kind = Literal["ok", "warn"]


def set_flash(request: Request, text: str, kind: Kind = "warn") -> None:
    """Сказать человеку, что произошло, — он увидит это после переадресации."""
    if not text:
        return
    request.session[_KEY] = {"text": text, "kind": kind}


@pass_context
def pop_flash(context: dict) -> dict | None:
    """Забрать сообщение и стереть его. Вызывается ровно из `base.html`."""
    request = context.get("request")
    if request is None or not hasattr(request, "session"):
        return None
    return request.session.pop(_KEY, None)
