"""Приём криптовалюты: три способа под одним интерфейсом (F70).

ПОЧЕМУ ТРИ, А НЕ ОДИН. Требование владельца: групп много, условия в них
разные, и кошельки тоже разные. Поэтому способы настраиваются списком, а
группа выбирает свой.

ГЛАВНОЕ РАЗЛИЧИЕ МЕЖДУ НИМИ — НЕ API, А КУРС:

* **CryptoBot** и **Wallet Pay** — посредники. Им можно назвать сумму В
  РУБЛЯХ, и они сами пересчитают её в криптовалюту по своему курсу на момент
  оплаты. Курс — их забота, риск скачка — тоже;
* **прямой перевод на TON-кошелёк** посредника не имеет. Комиссии нет
  совсем, но и пересчитывать некому: сумма указывается в TON.

ПОЭТОМУ КУРС МЫ НЕ СЧИТАЕМ И НЕ ТЯНЕМ ИЗ ИНТЕРНЕТА. Товар для прямого
перевода обязан быть оценён в TON владельцем. Сходить за курсом на
сторонний сервис означало бы: чужой сервис врёт или лежит — владелец молча
недополучает деньги на каждой продаже, и заметит это через месяц по
сходящейся не туда выручке. Явный отказ на этапе настройки честнее.

ОПРОС ВМЕСТО ВЕБХУКОВ. Все три способа проверяются опросом статуса, а не
входящим вызовом. Так система не обязана торчать наружу ради приёма денег:
публичная поверхность — это пересмотр модели угроз (см. F73/F74), и
оплачивать им удобство одного провайдера незачем. Опрос идёт через очередь
задач фазы 11, поэтому переживает рестарт.
"""

from __future__ import annotations

from dataclasses import dataclass

KIND_CRYPTOBOT = "cryptobot"
KIND_WALLETPAY = "walletpay"
KIND_TON_DIRECT = "ton_direct"

KINDS = (KIND_CRYPTOBOT, KIND_WALLETPAY, KIND_TON_DIRECT)

# Кто умеет принимать сумму в фиате и пересчитать сам.
FIAT_CAPABLE = (KIND_CRYPTOBOT, KIND_WALLETPAY)

STATUS_PENDING = "pending"
STATUS_PAID = "paid"
STATUS_EXPIRED = "expired"


class RailError(RuntimeError):
    """Провайдер не смог выставить счёт или ответил непонятным."""


@dataclass(frozen=True)
class CryptoInvoice:
    """Счёт у провайдера. `pay_url` — то, что показываем человеку."""

    external_id: str
    pay_url: str
    # Сумма и валюта, В КОТОРЫХ реально выставлен счёт. Для посредников это
    # фиат, для прямого перевода — TON. Хранится, чтобы в заказе было видно,
    # за что человек платил, а не только сколько это стоило в рублях.
    amount: str
    asset: str
